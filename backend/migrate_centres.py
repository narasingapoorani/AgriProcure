        # Create a code-to-centre map
        existing_centres = {c.code: c for c in ProcurementCentre.query.all()}
        inserted_count = 0
        updated_count = 0

        # Also remove old non-Tamil Nadu dummy centres that have no bookings
        for old_c in ProcurementCentre.query.all():
            if old_c.code not in [d['code'] for d in TAMIL_NADU_CENTRES]:
                # If this centre has bookings, remap bookings to target_id or first new centre
                old_bookings = Booking.query.filter_by(centre_id=old_c.id).all()
                if old_bookings:
                    print(f"  Remapping {len(old_bookings)} bookings from old centre {old_c.name} (ID {old_c.id})")
